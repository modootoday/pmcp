import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";
import { validatePassword } from "./password.mjs";

const require = createRequire(join(resolve(process.argv[2]), "package.json"));
const bcrypt = require("bcryptjs");
const checks = [];
const password = validatePassword("Fixture password");
const hash = await bcrypt.hash(password, 4);
assert.match(hash, /^\$2[ab]\$04\$/);
assert.equal(hash.length, 60);
checks.push("async hash creates a valid cost-4 fixture digest");
assert.equal(await bcrypt.compare(password, hash), true);
checks.push("async compare accepts the matching password");
assert.equal(await bcrypt.compare("Wrong password", hash), false);
checks.push("async compare rejects a different password");
assert.equal(bcrypt.getRounds(hash), 4);
checks.push("stored cost is readable for a future rehash decision");
const boundary = "가".repeat(24);
assert.equal(Buffer.byteLength(boundary, "utf8"), 72);
assert.equal(validatePassword(boundary), boundary);
checks.push("UTF-8 guard accepts exactly 72 bytes");
assert.throws(() => validatePassword(`${boundary}x`), RangeError);
assert.throws(() => validatePassword("a".repeat(73)), RangeError);
checks.push("UTF-8 guard rejects oversized multibyte and ASCII passwords");
assert.throws(() => validatePassword(42), TypeError);
checks.push("password guard rejects non-string inputs");
console.log(JSON.stringify({ checks }));
