// Source of .opencode/plugins/pmcp.js. opencode loads project plugins without trust; this one
// only forwards each hook to hook.mjs, so the policy stays in the lock-pinned bundle. Its imports
// use single quotes: the hook body carries this text, and its scan for heavy imports reads "node:.
export const PLUGIN_TEMPLATE = `// Generated by pmcp project from pmcp.toml [hooks]; edit pmcp.toml, not this file.
import { spawn } from 'node:child_process';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const HOOK = join(ROOT, ".agents/pmcp-hooks/hook.mjs");
const TIMEOUT_MS = __TIMEOUTS__;

// Resolves the hook's answer, or null when it could not run or answered nonsense.
function ask(event, payload) {
  if (!(event in TIMEOUT_MS)) return Promise.resolve({});
  return new Promise((done) => {
    const child = spawn("node", [HOOK, "opencode", event], {
      cwd: ROOT,
      stdio: ["pipe", "pipe", "ignore"],
    });
    let out = "";
    const timer = setTimeout(() => child.kill(), TIMEOUT_MS[event]);
    child.stdout.on("data", (chunk) => {
      out += chunk;
    });
    child.on("error", () => {
      clearTimeout(timer);
      done(null);
    });
    child.on("close", (code) => {
      clearTimeout(timer);
      try {
        done(code === 0 ? JSON.parse(out || "{}") : null);
      } catch {
        done(null);
      }
    });
    child.stdin.end(JSON.stringify(payload));
  });
}

export const Pmcp = async ({ directory, serverUrl }) => {
  // The server this session runs on, so pmcp sessions send --wake can prompt it while idle.
  const server = serverUrl ? String(serverUrl) : undefined;
  // queued: notes not yet shown; showing: notes every model call of this turn carries. A turn
  // can make several model calls (opencode's first is a small title call), so a note shown
  // once is kept until the next prompt starts a new turn.
  const queued = new Map();
  const showing = new Map();
  const hold = (session, text) => {
    if (session && text) queued.set(session, [...(queued.get(session) ?? []), text]);
  };
  return {
    "tool.execute.before": async (input, output) => {
      const answer = await ask("before_tool", { input, args: output.args, directory });
      // A tool call goes ahead only on a clear answer, as with the other runtimes' guards.
      if (!answer) throw new Error("pmcp hook did not answer; the call was refused");
      if (answer.deny) throw new Error(answer.deny);
    },
    "tool.execute.after": async (input, output) => {
      const answer = await ask("after_tool", { input, directory });
      if (answer?.context) output.output = \`\${output.output ?? ""}\\n\\n\${answer.context}\`;
    },
    "chat.message": async (input) => {
      showing.delete(input.sessionID);
      const answer = await ask("prompt", { input, directory });
      hold(input.sessionID, answer?.context);
    },
    "experimental.chat.system.transform": async (input, output) => {
      const session = input.sessionID;
      const notes = [...(showing.get(session) ?? []), ...(queued.get(session) ?? [])];
      queued.delete(session);
      if (notes.length === 0) return;
      showing.set(session, notes);
      output.system.push(notes.join("\\n\\n"));
    },
    event: async ({ event }) => {
      if (event.type === "session.created") {
        const answer = await ask("session_start", { ...event, directory, serverUrl: server });
        hold(event.properties?.sessionID, answer?.context);
      }
      if (event.type === "session.idle") await ask("stop", { ...event, directory });
    },
  };
};
`;
